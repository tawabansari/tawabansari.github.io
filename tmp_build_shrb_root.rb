A fixed share or turn of water.

### شُرْب

The act or manner of drinking itself.

### مَشْرَب

A place, share, or specific path of drinking.

### شَارِب

One who drinks.

## 17. Conclusion

The root ش ر ب in the Qur'an denotes drinking and concepts connected to it. This root looks at the event from the angle of the drinker, while س ق ي speaks more about delivering or providing drink.

The derivatives of the root have different fields:

* شَرِبَ: the act of drinking itself;
* شَرَاب: what is drunk;
* شِرْب: a share or turn of water;
* شُرْب: the act or quality of drinking;
* مَشْرَب: the place or share of access to drinking;
* شَارِب: drinker.

The uses of the Qur'an show:

* شَرَاب is a general word and does not only point to alcoholic drink;
* the drink may be water, the substance that comes out from the bee, pure heavenly drink, or boiling water of punishment;
* شِرْب in the story of the she-camel of Salih expresses the share and turn of water;
* مَشْرَب in the story of the twelve springs is the place or share of drinking for every group;
* شُرْبَ الْهِيمِ compares the manner of drinking of the people of Hell to the him;
* أُشْرِبُوا in the story of the calf is a metaphor for attachment penetrating into the heart;
* drinking does not necessarily lead to being quenched, pleasure, or health.

The final definition of the root is:

**ش ر ب denotes drinking and receiving liquid from the side of the drinker. Its derivatives may express the drink itself, the act of drinking, the drinker, a share of water, or the place of access to drinking. The type of liquid, the quality of drinking, and its result are known from the construction and context of each verse, not from the root alone.**
