# Qur'anic Root SH R B

## 1. Short Introduction to the Root

The root ش ر ب in the Qur'an denotes drinking, taking in drink, a drink, a share of water, and a place or means of access to water.

The center of this root is the act of the drinker: a person or creature brings a liquid into the mouth and drinks it. From this angle, ش ر ب differs from the root س ق ي:

* س ق ي speaks more about giving, delivering, or providing drink;
* ش ر ب focuses more on the act of receiving and drinking from the side of the drinker.

At the same time, shurb should not be defined as "complete absorption into cells," "frequency internalization," or "fluid digestion." In its basic meaning, drinking is bringing liquid into the body. Absorption, digestion, thirst-quenching, or psychological and bodily effect are possible outcomes of it; they are not obtained from the root alone.

The short and cautious definition of the root is:

**ش ر ب denotes drinking and receiving liquid from the side of the drinker. Its derivatives may express the drink itself, the act of drinking, a share of water, or the place and path of access to drinking.**

## 2. Important Forms and Derivatives of the Root

### شَرِبَ / يَشْرَبُ

He drank; he took a liquid into the mouth and swallowed it.

### اِشْرَبُوا

Plural command: drink.

### شَرَاب

Something that is drunk; drink or beverage.

شَرَاب in the Qur'an is a general word, and from the word itself one cannot conclude that the drink is alcoholic. The type of drink is known from context, descriptions, and accompanying words.

### شِرْب

A fixed share, turn, or right in the use of water.

This form appears in the story of the she-camel of Salih.

### شُرْب

The act or manner of drinking itself.

In the construction "شُرْبَ الْهِيمِ," the quality and state of drinking is compared with the drinking of the him.

### مَشْرَب

A place, path, share, or station of drinking.

In the story of the twelve springs, every group knows its own mashrab.

### شَارِب

Drinker.

### شَارِبُون / شَارِبِين

Drinkers.

## 3. Reference Cards for Qur'anic Derivatives

### شَرِبَ

He drank a liquid.

### شَرَاب

Drink; its type and quality become clear from context.

### شِرْب

A fixed share or turn of water.

### شُرْب

The act or manner of drinking.

### مَشْرَب

A place, share, or specific path of drinking.

### شَارِب

One who drinks.

## 4. The Semantic Core of the Root

The semantic core of the root is:

**Receiving and swallowing liquid from the side of the drinker.**

This core can be seen on several levels:

* the verb شَرِبَ expresses the act of drinking itself;
* شَرَاب is what is drunk;
* شُرْب is the name of the act or quality of drinking itself;
* شِرْب is the share and turn according to which drinking from a shared source takes place;
* مَشْرَب is the specific point, path, or share of access to water.

In all of these forms there is a relation to drinking, but they should not all be reduced to one single meaning. A share of water, a drink, a place of drinking, and the act of drinking itself are four distinct concepts.

## 5. The Material Image of the Root

The main material image of this root is a human being or animal drinking water or another liquid from a vessel, spring, or source.

This event has several parts:

* there is a liquid to drink;
* the drinker gains access to it;
* the drinker receives it;
* the drinker swallows it.

In an environment where water is limited, a second image also becomes important: groups or animals approach the water source at separate times or places, and each has a specific share or turn. This image is seen in شِرْب and مَشْرَب.

But this simple event should not be turned into a pump suction, data transfer, frequency absorption, or hydraulic system. Such comparisons are not the lexical meaning of the word.

## 6. Use of the Root in Arabic

In Arabic, شَرِبَ الْمَاءَ means he drank water. The drink is usually the object of the verb.

شَرَاب is a general noun for something that is drunk. This word may refer to water, milk, fruit drink, khamr, heavenly drink, or a drink of punishment.

In modern Persian, "sharab" mostly suggests alcoholic drink. This Persian restriction should not be imposed on the Qur'anic Arabic meaning. In many verses, "drink" or "beverage" is more accurate.

شِرْب, in environments dependent on wells and shared sources, may refer to a share or turn of water. مَشْرَب may also be the place or share from which drinking happens.

## 7. Challenges in Understanding and Translation

### Restricting شَرَاب to alcoholic drink

This is one of the most important translation errors. The Qur'an uses شَرَاب for different drinks. For example:

* شَرَابًا طَهُورًا: a pure drink;
* شَرَابٌ مُخْتَلِفٌ أَلْوَانُهُ: a drink of different colors;
* شَرَابٌ مِنْ حَمِيمٍ: a drink from boiling water.

Therefore "wine" is appropriate only when the context truly indicates the known drink of khamr or something similar.

### Defining shurb as full absorption and digestion

Drinking is accompanied by the entering of liquid into the body, but the root alone does not speak about digestion, cellular absorption, biological change, or final effect.

In some verses, drinking does not even lead to being quenched. Therefore thirst-quenching or saturation should not be placed inside the basic definition.

### Mixing شِرْب and شُرْب

The vowel pattern of the word in the Qur'an matters:

* شِرْب: a share or turn of water;
* شُرْب: the act or quality of drinking.

In unvoweled text both are written "شرب," but context and recitation separate their meanings.

### Turning مَشْرَب into a technical station

مَشْرَب in Al-Baqarah 2:60 may be the place, path, or specific share of drinking for each group. Translations such as "hydration terminal" or "feeding portal" are not natural or Qur'anic.

### Importing a positive meaning into the root itself

A drink may be pleasant or painful. The Qur'an speaks of heavenly and hellish drinks alike.

So shurb is not, in itself, mercy, purity, or life-giving. The type of liquid and its result are understood from context.

## 8. Methodological Note

In examining each verse, one should ask:

* Who drinks?
* What is drunk?
* Is the drink explicitly mentioned?
* Is the speech about drinking itself, or about a share and turn of water?
* Is the mashrab a place, source, or share?
* From which description or construction is the quality of the drink understood?
* Is the drinking literal or metaphorical?

One should also distinguish between these levels:

**Direct meaning:** drinking or drink.

**State of access:** share, turn, or place of drinking.

**Result:** being quenched, pleasure, pain, illness, or punishment.

**Metaphorical use:** the penetration of an attachment or inclination into the heart.

Result and metaphor should not be inserted into the basic translation of the root.

## 9. Qur'anic Uses of the Root

## Drinking from the provision of The God

### Al-Baqarah 2:60

قَدْ عَلِمَ كُلُّ أُنَاسٍ مَشْرَبَهُمْ كُلُوا وَاشْرَبُوا مِنْ رِزْقِ اللَّهِ وَلَا تَعْثَوْا فِي الْأَرْضِ مُفْسِدِينَ

Every group knew its place or share of drinking. Eat and drink from the provision of The God, and do not act corruptly in the earth, spreading disorder.

In this verse, two forms of the root appear:

* مَشْرَبَهُمْ;
* اشْرَبُوا.

"مَشْرَبَهُمْ" points to the known place or share of each group from the springs. "اشْرَبُوا" is the command to drink.

The attached pronoun "هُمْ" shows the specification and relation of each mashrab to its respective group, but absolute ownership or a special physical feature of the water should not be inferred from this attachment.

## Eating and drinking until dawn

### Al-Baqarah 2:187

وَكُلُوا وَاشْرَبُوا حَتَّىٰ يَتَبَيَّنَ لَكُمُ الْخَيْطُ الْأَبْيَضُ مِنَ الْخَيْطِ الْأَسْوَدِ مِنَ الْفَجْرِ

And eat and drink until the white thread of dawn becomes clear to you from the black thread of night.

"كُلُوا وَاشْرَبُوا" places eating and drinking beside one another. These two verbs express two main parts of nourishment, but one should not conclude from this pairing that أ ك ل is always only for solids and ش ر ب always only for liquids with a completely technical boundary. This distinction is clear in common usage, but language can have figurative expansions.

## Prohibition from drinking from the river

### Al-Baqarah 2:249

إِنَّ اللَّهَ مُبْتَلِيكُمْ بِنَهَرٍ فَمَنْ شَرِبَ مِنْهُ فَلَيْسَ مِنِّي وَمَنْ لَمْ يَطْعَمْهُ فَإِنَّهُ مِنِّي إِلَّا مَنِ اغْتَرَفَ غُرْفَةً بِيَدِهِ

The God is testing you with a river; whoever drinks from it is not of me, and whoever does not taste it is of me, except one who scoops a handful with his hand.

In this verse, شَرِبَ is the act of drinking from the river. Beside it comes "يَطْعَمْهُ," which shows that the root ط ع م can also be used for tasting or consuming liquid.

This verse warns that simple comparisons such as "أكل is only solid and شرب only liquid" do not always explain all the subtlety of Qur'anic language.

## Drinking of livestock and human beings

### An-Nahl 16:10

هُوَ الَّذِي أَنْزَلَ مِنَ السَّمَاءِ مَاءً لَكُمْ مِنْهُ شَرَابٌ وَمِنْهُ شَجَرٌ فِيهِ تُسِيمُونَ

He is The One who sent down water from the sky for you; from it there is drink for you, and from it grows vegetation in which you pasture your livestock.

شَرَاب in this verse points to water that is drunk. This use clearly shows that شَرَاب in the Qur'an is not only khamr or alcoholic drink.

## The drink that comes out from the bellies of bees

### An-Nahl 16:69

يَخْرُجُ مِنْ بُطُونِهَا شَرَابٌ مُخْتَلِفٌ أَلْوَانُهُ فِيهِ شِفَاءٌ لِلنَّاسِ

From their bellies comes out a drink of different colors, in which there is healing for people.

شَرَاب in this verse points to the drinkable substance that comes out from the bee. The verse itself does not use the name "honey," although its known referent is honey.

The different colors and the presence of healing come from other parts of the verse, not from the word شَرَاب itself.

## Pure heavenly drink

### Al-Insan 76:21

وَسَقَاهُمْ رَبُّهُمْ شَرَابًا طَهُورًا

And their Lord gave them a pure drink to drink.

In this verse:

* سَقَاهُمْ expresses the act of giving drink;
* شَرَابًا names the drink;
* طَهُورًا gives its quality.

The co-presence of س ق ي and ش ر ب clarifies the difference between the two roots: one is the act of delivering drink, and the other is the name of what is drunk.

## Drink mixed with kafur

### Al-Insan 76:5

إِنَّ الْأَبْرَارَ يَشْرَبُونَ مِنْ كَأْسٍ كَانَ مِزَاجُهَا كَافُورًا

The righteous drink from a cup whose mixture is kafur.

The verb "يَشْرَبُونَ" expresses the act of the drinkers. The nature of kafur and the reality of the drink of the afterlife should remain open and should not be restricted to the known earthly substance.

## Drink mixed with ginger

### Al-Insan 76:17

وَيُسْقَوْنَ فِيهَا كَأْسًا كَانَ مِزَاجُهَا زَنْجَبِيلًا

And in it they are given a cup to drink whose mixture is ginger.

Here the verb is from س ق ي, and the cup is what is given as drink. The connection between these verses shows that saqy and shurb are in one field, but they speak from two sides of the event.

## A pleasurable drink for the drinkers

### As-Saffat 37:45 to 46

يُطَافُ عَلَيْهِمْ بِكَأْسٍ مِنْ مَعِينٍ
بَيْضَاءَ لَذَّةٍ لِلشَّارِبِينَ

A cup of flowing drink is passed around them; white and pleasurable for the drinkers.

"الشَّارِبِينَ" is a plural active participle. The drink's being pleasurable is understood from "لَذَّةٍ," not from shurb itself.

### Muhammad 47:15

وَأَنْهَارٌ مِنْ خَمْرٍ لَذَّةٍ لِلشَّارِبِينَ

And rivers of khamr, pleasurable for the drinkers.

In this verse, the word "خَمْر" itself appears. This shows that شَرَاب and خَمْر are not complete synonyms:

* شَرَاب is the general word for drink;
* خَمْر is the name of a specific kind of drink.

## Drinks of punishment

### Yunus 10:4

لَهُمْ شَرَابٌ مِنْ حَمِيمٍ وَعَذَابٌ أَلِيمٌ بِمَا كَانُوا يَكْفُرُونَ

For them there is a drink from boiling water, and a painful punishment because of how they used to cover truth.

شَرَاب is the general name for a drink, and "مِنْ حَمِيمٍ" specifies its type.

### Sad 38:57

هَٰذَا فَلْيَذُوقُوهُ حَمِيمٌ وَغَسَّاقٌ

This, then let them taste it: boiling water and ghassaq.

Here the word شَرَاب does not appear, even though the verse speaks of materials of punishment. This is an important reminder that not every liquid or tasted thing is named by the root ش ر ب.

## Drinking boiling water

### Al-Waqi'ah 56:51 to 55

ثُمَّ إِنَّكُمْ أَيُّهَا الضَّالُّونَ الْمُكَذِّبُونَ
لَآكِلُونَ مِنْ شَجَرٍ مِنْ زَقُّومٍ
فَمَالِئُونَ مِنْهَا الْبُطُونَ
فَشَارِبُونَ عَلَيْهِ مِنَ الْحَمِيمِ
فَشَارِبُونَ شُرْبَ الْهِيمِ

Then you, O straying deniers, will eat from a tree of zaqqum, and fill your bellies from it, and drink over it from boiling water; then you will drink like the drinking of the him.

In these verses:

* فَشَارِبُونَ is a plural active participle;
* شُرْبَ is a verbal noun and expresses the quality of drinking in the comparison;
* الْهِيمِ is the side of the comparison.

Him is interpreted in lexical sources as extremely thirsty camels or camels afflicted by an illness related to constant thirst. But the Qur'an itself does not give a medical explanation about cellular non-absorption or a specific disease.

A cautious translation:

**Then you will drink like the drinking of severely thirsty camels.**

## The she-camel's share of water

### Ash-Shu'ara 26:155

قَالَ هَٰذِهِ نَاقَةٌ لَهَا شِرْبٌ وَلَكُمْ شِرْبُ يَوْمٍ مَعْلُومٍ

He said: This is a she-camel; for her is a share of water, and for you is the share of a known day.

شِرْب here points to a share or turn in the use of water. The water itself is divided temporally between the sides.

It is better to translate it as "share of water" or "turn of water," not "the act of drinking."

### Al-Qamar 54:28

وَنَبِّئْهُمْ أَنَّ الْمَاءَ قِسْمَةٌ بَيْنَهُمْ كُلُّ شِرْبٍ مُحْتَضَرٌ

And inform them that the water is divided between them; every share of water is to be attended in its turn.

"قِسْمَةٌ" expresses that the water is divided, and "كُلُّ شِرْبٍ مُحْتَضَرٌ" emphasizes the observance of every turn or share.

The legal and social weight of شِرْب becomes clear from this structure, not only from its morphological pattern.

## Being made to drink attachment to the calf

### Al-Baqarah 2:93

وَأُشْرِبُوا فِي قُلُوبِهِمُ الْعِجْلَ بِكُفْرِهِمْ

And because of their covering of truth, the calf was made to be drunk into their hearts.

This phrase is a compressed metaphorical use. It is clear that the physical body of the calf did not enter the hearts. The intended meaning is the intense penetration of attachment, love, or inclination toward the calf into their hearts.

A more natural translation:

**And because of their covering of truth, love of the calf was made to penetrate into their hearts.**

Or with preservation of the image:

**And because of their covering of truth, the calf was made to be drunk into their hearts.**

Then in explanation:

**That is, attachment to the calf entered their hearts so deeply that it settled inside like a drink.**

This metaphor should not be turned into magnetism, frequency, cellular sediment, or a biological mechanism.

## 10. Examination of Important Derivatives in the Qur'an

### شَرِبَ

It is the verb of drinking. The subject is the drinker, and the drink may be expressed through an object or through the particle "مِن."

### شَرَاب

It is a general noun for drink. The Qur'an uses it for water, the substance that comes out from the bee, pure drink, and boiling drink.

Therefore شَرَاب should not always be translated as "wine."

### شِرْب

It is a share and turn of water. Its Qur'anic use in the story of the she-camel of Salih carries the weight of division and right of access.

### شُرْب

It is the verbal noun of drinking. In "شُرْبَ الْهِيمِ," it expresses the type and quality of drinking in the form of a comparison.

### مَشْرَب

In Al-Baqarah 2:60, it is the known place or share of drinking for each group.

### شَارِب

It is the active participle and denotes one who performs drinking.

## 11. Grammatical and Structural Notes

### Drink with the particle "مِن"

In phrases such as:

يَشْرَبُونَ مِنْ كَأْسٍ
فَشَارِبُونَ عَلَيْهِ مِنَ الْحَمِيمِ
فَمَنْ شَرِبَ مِنْهُ

"مِن" may express the source or the thing from which drinking takes place.

Its exact role should be understood from the structure of each verse and should not be turned into a physical law about partial or complete entry.

### Direct object

In some structures, what is drunk can be the direct object. The object may also be omitted when the drink is clear from context.

### شَرَاب as a noun

Accompanying descriptions and constructions specify the type of drink:

* طَهُورًا;
* مِنْ حَمِيمٍ;
* مُخْتَلِفٌ أَلْوَانُهُ.

Thus purity, heat, or different colors are not part of the fixed meaning of شَرَاب.

### The annexation of مَشْرَب

In:

مَشْرَبَهُمْ

The pronoun "هُمْ" expresses the relation of each place or share of drinking to the relevant group. This annexation is about the order of access, not necessarily personal ownership of the source.

### The construction شُرْبَ الْهِيمِ

شُرْب is a verbal noun and الْهِيمِ is the genitive complement. The construction compares the drinking of the people of Hell to the drinking of the him.

From this structure, no definite medical diagnosis for him should be extracted.

### The passive construction أُشْرِبُوا

In Al-Baqarah 2:93, the verb is passive, and the Children of Israel are the recipients of a metaphorical state. "فِي قُلُوبِهِمُ" expresses the place of penetration in imaginal language.

## 12. ش ر ب Compared with Near Roots

### ش ر ب (شَرِبَ) compared with س ق ي (سَقَى)

ش ر ب speaks from the angle of the drinker.

س ق ي speaks from the angle of the one who delivers or provides drink.

For example:

وَسَقَاهُمْ رَبُّهُمْ شَرَابًا طَهُورًا

The Lord gives drink, and they receive the drink.

Still, saqy is not always direct delivery to the mouth, and shurb does not speak about full biological absorption.

### ش ر ب (شَرِبَ) compared with أ ك ل (أَكَلَ)

In common usage:

* أكل relates to eating;
* شرب relates to drinking.

The Qur'an repeatedly says:

كُلُوا وَاشْرَبُوا

But the root ط ع م appears in Al-Baqarah 2:249 about river water as well. So the boundary between words of consumption and tasting is not always only solid and liquid.

### ش ر ب (شَرِبَ) compared with ذ و ق (ذَاقَ)

ذوق focuses on tasting and experiencing the quality of something, and in the Qur'an it is also used metaphorically for punishment, mercy, death, and non-food matters.

شرب focuses on drinking liquid.

But one should not say that dhawq always means a small amount and shurb always means complete swallowing; this distinction is useful in some uses, but it is not an absolute law.

### ش ر ب (شَرِبَ) compared with ط ع م (طَعِمَ)

طعم can convey eating, tasting, or experiencing flavor. In Al-Baqarah 2:249 it is also used about river water.

شرب directly emphasizes drinking; طعم can focus on consumption or testing taste from another angle.

### ش ر ب (شَرِبَ) compared with ر و ي (رَوِيَ)

Shurb is the act of drinking.

Rayy and riwa' relate to becoming quenched and the removal of thirst.

One may drink and yet not be quenched, as in the image of shurb al-him. Therefore the result of being quenched is not guaranteed inside shurb itself.

## 13. The Link between ف ج ر, ع ي ن, and ش ر ب in Al-Baqarah 2:60

Al-Baqarah 2:60 brings three roots together in one event:

فَانْفَجَرَتْ مِنْهُ اثْنَتَا عَشْرَةَ عَيْنًا قَدْ عَلِمَ كُلُّ أُنَاسٍ مَشْرَبَهُمْ كُلُوا وَاشْرَبُوا مِنْ رِزْقِ اللَّهِ

In this structure:

* ف ج ر expresses the event of water breaking out;
* ع ي ن names the springs themselves;
* ش ر ب expresses the place or share of drinking and the act of drinking.

These three roots show three different angles of one event:

1. Water finds a way and comes out;
2. springs appear as specific sources;
3. the groups know their place of drinking and drink from the water.

This linguistic coordination is worth examining, but it should not be turned into a theory about three stages of energy engineering, hydraulic nozzles, or thermodynamic stability.

## 14. Shurb as a Metaphor of Penetration

The phrase "وَأُشْرِبُوا فِي قُلُوبِهِمُ الْعِجْلَ" shows that Qur'anic language can use drinking for the deep penetration of an affection or inclination.

The feature of this metaphor is that after a drink enters, it is no longer seen from outside; rather, it settles within. For this reason, shurb can be a fitting image for an attachment that has penetrated into the heart.

But the precise meaning of the verse is understood from the complete construction:

* the calf is not the outward object of the verb;
* the hearts are the metaphorical place of penetration;
* covering truth is the ground of this attachment.

A suitable explanation:

**Love and devotion to the calf penetrated into their hearts.**

Not:

**The frequency of the calf dissolved in their cardiac tissue.**

