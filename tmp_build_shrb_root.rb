    text.gsub(/(بقره|نحل|انسان|صافات|محمد|یونس|ص|واقعه|شعرا|قمر)\s+([۰-۹0-9]+):([۰-۹0-9]+)/) do
      sura, chapter, ayah = $1, $2, $3
      slug = SLUGS[sura][0]
      num = ayah.tr("۰۱۲۳۴۵۶۷۸۹", "0123456789").to_i
      %(<a href="/quran-reflection/fa/#{slug}/#ayah-#{format('%03d', num)}">#{esc($&)}</a>)
    end
  else
    text.gsub(/(Al-Baqarah|An-Nahl|Al-Insan|As-Saffat|Muhammad|Yunus|Sad|Al-Waqi'ah|Ash-Shu'ara|Al-Qamar)\s+([0-9]+):([0-9]+)/) do
      sura, _chapter, ayah = $1, $2, $3
      slug = EN_SLUGS[sura][0]
      %(<a href="/quran-reflection/en/#{slug}/#ayah-#{format('%03d', ayah.to_i)}">#{esc($&)}</a>)
    end
  end
end

def inline_format(text, lang)
  s = esc(text)
  s = s.gsub(/\*\*(.+?)\*\*/, '<strong>\1</strong>')
  link_ref(s, lang)
end

def card_section(cards, lang)
  title = lang == :fa ? "۳. کارت‌های قابل ارجاع برای مشتق‌های قرآنی" : "3. Reference Cards for Qur'anic Derivatives"
  card_word = lang == :fa ? "صورت" : "Form"
  quran = lang == :fa ? "در قرآن: بلی" : "In Qur'an: yes"
  html = %(<section id="section-3" class="root-forms-card"><h2>#{esc(title)}</h2><div class="morphology-grid">\n)
  cards.each do |form, note|
    html << %(<a class="morph-card" href="#section-10"><div class="morph-card-header"><span>#{card_word}</span><span>#{quran}</span></div><div class="morph-form">#{esc(form)}</div><p class="morph-note">#{esc(note)}</p></a>\n)
  end
  html << "</div></section>\n"
end

def parse(raw, lang)
  lines = raw.lines.map(&:chomp)
  title = lines.shift.sub(/^#\s*/, "")
  sections = []
  current = nil
  cards = []
  i = 0
  while i < lines.length
    line = lines[i]
    if line.start_with?("## ")
      heading = line.sub(/^##\s*/, "")
      if heading.match?(/\A([0-9]+|[۰-۹]+)\./) || current.nil?
        sections << current if current
        current = { title: heading, blocks: [] }
      else
        current[:blocks] << "### #{heading}"
      end
    elsif current
      if current[:title].include?("کارت") || current[:title].include?("Reference Cards")
        if line.start_with?("### ")
          form = line.sub(/^###\s*/, "")
          note = ""
          j = i + 1
          while j < lines.length && lines[j].strip.empty?
            j += 1
          end
          note = lines[j].to_s if j < lines.length && !lines[j].start_with?("#")
          cards << [form, note]
        end
      else
        current[:blocks] << line
      end
    end
    i += 1
  end
  sections << current if current

  html = +""
  toc = sections.map.with_index do |sec, idx|
    %(<li><a href="#section-#{idx + 1}">#{esc(sec[:title])}</a></li>)
  end.join("\n")

  sections.each_with_index do |sec, idx|
    if idx == 2 && !cards.empty?
      html << card_section(cards, lang)
      next
    end
    html << %(<section id="section-#{idx + 1}" class="root-section"><h2>#{esc(sec[:title])}</h2>\n)
    html << render_blocks(sec[:blocks], lang)
    html << "</section>\n"
  end
  [title, toc, html]
end

def render_blocks(lines, lang)
  out = +""
  pending = []
  para = []
  i = 0
  flush_para = lambda do
    unless para.empty?
      out << "<p>#{inline_format(para.join(' '), lang)}</p>\n"
      para.clear
    end
  end
  flush_list = lambda do
    unless pending.empty?
      out << "<ul>"
      pending.each { |li| out << "<li>#{inline_format(li, lang)}</li>" }
      out << "</ul>\n"
      pending.clear
    end
  end

  while i < lines.length
    line = lines[i]
    if line.strip.empty?
      flush_para.call
      flush_list.call
      i += 1
      next
    end
    if line.start_with?("### ")
      flush_para.call
      flush_list.call
      out << "<h3>#{esc(line.sub(/^###\s*/, ''))}</h3>\n"
      i += 1
      next
    end
    if line.start_with?("* ")
      flush_para.call
      pending << line.sub(/^\*\s*/, "")
      i += 1
      next
    end
    if line.match?(/^\d+\.\s+/)
      flush_para.call
      pending << line.sub(/^\d+\.\s+/, "")
      i += 1
      next
    end
    if verse_candidate?(line) && line.length > 25 && !line.match?(/[A-Za-z]/)
      flush_para.call
      flush_list.call
      arabic_lines = []
      while i < lines.length && verse_candidate?(lines[i]) && lines[i].length > 10 && !lines[i].match?(/[A-Za-z]/) && !lines[i].start_with?("#")
        arabic_lines << lines[i]
        i += 1
      end
      ref = verse_ref_for(arabic_lines.join("\n"))
      translation = []
      if ref
        while i < lines.length && lines[i].strip.empty?
          i += 1
        end
        while i < lines.length && !lines[i].strip.empty? && !lines[i].start_with?("#") && !lines[i].start_with?("* ") && !lines[i].match?(/^\d+\.\s+/) && !verse_candidate?(lines[i])
          translation << lines[i]
          i += 1
        end
      end
      if ref
        out << %(<blockquote class="arabic-quote"><p>#{arabic_lines.map { |l| esc(l) }.join("<br>")}</p></blockquote>\n)
        out << %(<p class="translation">#{inline_format(translation.join(" "), lang)}</p>\n) unless translation.empty?
        slug, ayah = ref
        label = if lang == :fa
          sura = SLUGS.find { |_k, v| v[0] == slug }&.first || slug
          chapter = slug.split("-").first.to_i.to_s.tr("0123456789", "۰۱۲۳۴۵۶۷۸۹")
          "#{sura} #{chapter}:#{ayah.to_s.tr('0123456789', '۰۱۲۳۴۵۶۷۸۹')}"
        else
          sura = EN_SLUGS.find { |_k, v| v[0] == slug }&.first || slug
          chapter = slug.split("-").first.to_i
          "#{sura} #{chapter}:#{ayah}"
        end
        out << %(<p class="verse-ref"><a href="/quran-reflection/#{lang}/#{slug}/#ayah-#{format('%03d', ayah)}">#{esc(label)}</a></p>\n)
      else
        out << %(<p class="arabic-large">#{arabic_lines.map { |l| esc(l) }.join("<br>")}</p>\n)
        translation.each { |t| out << "<p>#{inline_format(t, lang)}</p>\n" }
      end
      next
    end
    para << line
    i += 1
  end
  flush_para.call
  flush_list.call
  out
end

